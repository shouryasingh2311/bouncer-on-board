"""Heuristics engine: Levenshtein typosquatting, age calculation, naming tropes, and provenance."""

from __future__ import annotations

from datetime import datetime, timezone
import json
from pathlib import Path
from typing import List, Optional, Set, Tuple


def levenshtein_distance(s1: str, s2: str) -> int:
    """Compute Levenshtein edit distance using standard library only."""
    if len(s1) < len(s2):
        return levenshtein_distance(s2, s1)
    if len(s2) == 0:
        return len(s1)

    previous_row = list(range(len(s2) + 1))
    for i, c1 in enumerate(s1):
        current_row = [i + 1]
        for j, c2 in enumerate(s2):
            insertions = previous_row[j + 1] + 1
            deletions = current_row[j] + 1
            substitutions = previous_row[j] + (c1 != c2)
            current_row.append(min(insertions, deletions, substitutions))
        previous_row = current_row
    return previous_row[-1]


_TOP_PYPI_NAMES: Optional[List[str]] = None
_TOP_NPM_NAMES: Optional[List[str]] = None


def get_top_packages(ecosystem: str) -> List[str]:
    """Load bundled top packages list for typosquatting checks."""
    global _TOP_PYPI_NAMES, _TOP_NPM_NAMES
    data_dir = Path(__file__).parent.parent / "data"

    if ecosystem.lower() == "pypi":
        if _TOP_PYPI_NAMES is None:
            p = data_dir / "top_pypi.json"
            if p.is_file():
                with open(p, "r", encoding="utf-8") as f:
                    _TOP_PYPI_NAMES = json.load(f)
            else:
                _TOP_PYPI_NAMES = ["requests", "urllib3", "numpy", "pandas", "flask", "django"]
        return _TOP_PYPI_NAMES
    else:
        if _TOP_NPM_NAMES is None:
            p = data_dir / "top_npm.json"
            if p.is_file():
                with open(p, "r", encoding="utf-8") as f:
                    _TOP_NPM_NAMES = json.load(f)
            else:
                _TOP_NPM_NAMES = ["express", "react", "react-dom", "lodash", "axios"]
        return _TOP_NPM_NAMES


def check_typosquat(package_name: str, ecosystem: str) -> Optional[Tuple[str, int]]:
    """Check if package_name is an edit distance <= 2 typosquat of a top package.

    Returns (top_package_matched, distance) if typosquat detected, else None.
    Identical names (dist == 0) return None.
    """
    pkg = package_name.strip().lower()
    top_list = get_top_packages(ecosystem)

    for top in top_list:
        clean_top = top.strip().lower()
        if pkg == clean_top:
            return None
        dist = levenshtein_distance(pkg, clean_top)
        if 1 <= dist <= 2:
            return (clean_top, dist)
    return None


def calculate_age_score(
    first_upload: Optional[datetime], min_age_days: int = 14
) -> Tuple[int, Optional[int]]:
    """Calculate risk score based on package age in days.

    Returns (score_increment, days_old).
    Weights: <7d: +50, <14d: +35, <30d: +15.
    """
    if not first_upload:
        # Unknown age: moderate signal
        return 15, None

    now = datetime.now(timezone.utc)
    if first_upload > now:
        age_days = 0
    else:
        age_days = (now - first_upload).days

    if age_days < 7:
        return 50, age_days
    elif age_days < min_age_days:
        return 35, age_days
    elif age_days < 30:
        return 15, age_days
    return 0, age_days


# Common naming tropes generated by LLMs or malware syndicates
TROPE_SUFFIXES = ("-utils", "-helper", "-ai", "-gpt", "-v2", "-pro", "-lib", "-client", "-tool", "-tools", "-api")
TROPE_PREFIXES = ("python-", "node-", "easy-", "fast-", "ai-", "smart-")


def check_naming_trope(package_name: str, ecosystem: str) -> Optional[Tuple[str, str]]:
    """Check if package matches an LLM naming trope based on a popular package.

    Returns (base_package, trope_pattern) or None.
    Example: requests-utils -> (requests, -utils)
    """
    pkg = package_name.strip().lower()
    top_list = get_top_packages(ecosystem)
    top_set: Set[str] = {t.strip().lower() for t in top_list}

    # Suffix check
    for sfx in TROPE_SUFFIXES:
        if pkg.endswith(sfx):
            base = pkg[: -len(sfx)]
            if base in top_set:
                return (base, sfx)

    # Prefix check
    for pfx in TROPE_PREFIXES:
        if pkg.startswith(pfx):
            base = pkg[len(pfx) :]
            if base in top_set:
                return (base, pfx)

    return None
