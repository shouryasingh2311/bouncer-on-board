"""Data models for BOB findings, decisions, and triage results."""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
import hashlib
from typing import Any, Dict, List, Optional


def mask_secret(value: str) -> str:
    """Mask secret data, keeping at most first 4 characters followed by ****.

    PROJECT.md Section 0 Rule 9: Secrets are never printed in full.
    Any evidence containing a secret is masked (first 4 chars + ****).
    """
    if not value:
        return ""
    if len(value) <= 4:
        return "****"
    return f"{value[:4]}****"


def compute_fingerprint(
    rule_id: str,
    file_path: Optional[str],
    line: Optional[int],
    evidence: str,
) -> str:
    """Compute deterministic SHA-256 fingerprint for a finding.

    sha256 of rule_id + file + line + masked evidence.
    """
    file_str = file_path or ""
    line_str = str(line) if line is not None else ""
    raw = f"{rule_id}:{file_str}:{line_str}:{evidence}"
    return hashlib.sha256(raw.encode("utf-8", errors="replace")).hexdigest()


@dataclass
class AITriage:
    """AI evaluation of a finding produced by local Gemma 4."""

    verdict: str  # likely_true_positive | likely_false_positive | uncertain
    explanation: str
    suggested_fix: str
    model: str

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class Finding:
    """Standardized finding generated by deterministic tools or built-in rules."""

    id: str  # e.g. BOB-0001
    rule_id: str  # e.g. PKG-NOT-FOUND, INJ-010
    source: str  # gitleaks | semgrep | osv | bob-builtin | bob-pkg-gate | bob-guard
    category: str  # package | secret | injection | code | dependency | config
    severity: str  # critical | high | medium | low | info
    title: str
    file: Optional[str]
    line: Optional[int]
    evidence: str  # Must be masked if containing sensitive data
    fingerprint: str = ""
    ai: Optional[AITriage] = None

    def __post_init__(self) -> None:
        if not self.fingerprint:
            self.fingerprint = compute_fingerprint(
                self.rule_id, self.file, self.line, self.evidence
            )

    def to_dict(self) -> Dict[str, Any]:
        data = asdict(self)
        if self.ai:
            data["ai"] = self.ai.to_dict()
        return data


@dataclass
class Decision:
    """Decision output for package checks and action interceptions."""

    action: str  # allow | warn | block
    score: int
    reasons: List[str] = field(default_factory=list)
    findings: List[Finding] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "action": self.action,
            "score": self.score,
            "reasons": self.reasons,
            "findings": [f.to_dict() for f in self.findings],
        }
